export function getTestIntro(test: Test): string {
  return flagshipContent[test.id]?.intro ?? test.description;
}

export function getTestTips(test: Test): string[] {
  const flagship = flagshipContent[test.id];
  if (flagship) return flagship.tips;

  const tips: string[] = [];
  test.bonusTypes.forEach((b) => {
    const pool = genericTips[b];
    tips.push(pool[0]);
  });
  test.bonusTypes.forEach((b) => {
    if (tips.length >= 4) return;
    const pool = genericTips[b];
    if (pool[1] && !tips.includes(pool[1])) tips.push(pool[1]);
  });
  return tips.slice(0, 4);
}
